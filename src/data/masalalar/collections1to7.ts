import type { CppCollection, CppLevel, CppProblem } from '../../types/masalalar';

interface ProblemSeed {
  title: string;
  statementUz: string;
  inputSpecUz: string;
  outputSpecUz: string;
  sampleInput: string;
  sampleOutput: string;
  difficulty: CppLevel;
  topicTag: string;
  starterCode?: string;
  hintUz: string;
  solutionCode: string;
  explanationUz: string;
}

function buildProblems(
  collectionId: string,
  prefix: string,
  seeds: ProblemSeed[],
): CppProblem[] {
  return seeds.map((s, idx) => {
    const num = idx + 1;
    const code = `${prefix}${num}`;
    return {
      id: `${collectionId}-${num}`,
      collectionId,
      number: num,
      code,
      title: s.title,
      statementUz: s.statementUz,
      inputSpecUz: s.inputSpecUz,
      outputSpecUz: s.outputSpecUz,
      sampleInput: s.sampleInput,
      sampleOutput: s.sampleOutput,
      difficulty: s.difficulty,
      topicTag: s.topicTag,
      starterCode:
        s.starterCode ??
        `#include <iostream>\nusing namespace std;\n\nint main() {\n    // ${code}: Yechim kodini shu yerga yozing\n    \n    return 0;\n}`,
      hintUz: s.hintUz,
      solutionCode: s.solutionCode,
      explanationUz: s.explanationUz,
    };
  });
}

